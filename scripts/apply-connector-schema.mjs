/**
 * Apply the Pirate Ship connector schema to Neon.
 *
 * Additive and idempotent: every statement is guarded with IF NOT EXISTS or a
 * duplicate-object catch, so re-running it is a no-op. It creates tables,
 * columns and indexes and never drops, alters or truncates anything.
 *
 * Deliberately NOT scripts/push-schema.mjs — that one begins with DROP TABLE
 * and would destroy the store.
 *
 * Usage:  node scripts/apply-connector-schema.mjs
 *         node scripts/apply-connector-schema.mjs --dry-run
 */

const DRY_RUN = process.argv.includes('--dry-run');

const DATABASE_URL = process.env.DATABASE_URL;
if (!DATABASE_URL) {
  console.error('DATABASE_URL not set. Load your .env first.');
  process.exit(1);
}

const parsed = new URL(DATABASE_URL.replace('postgresql://', 'http://'));
const host = parsed.hostname.replace('-pooler.', '.'); // non-pooler for DDL

async function query(sql) {
  const res = await fetch(`https://${host}/sql`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Neon-Connection-String': DATABASE_URL.split('&channel_binding')[0],
    },
    body: JSON.stringify({ query: sql, params: [] }),
  });
  if (!res.ok) {
    throw new Error(`${res.status}: ${await res.text()}`);
  }
  return res.json();
}

const steps = [
  [
    'enum api_key_permission',
    `DO $$ BEGIN
       CREATE TYPE "api_key_permission" AS ENUM('read', 'read_write');
     EXCEPTION WHEN duplicate_object THEN NULL; END $$`,
  ],

  [
    'table api_keys',
    `CREATE TABLE IF NOT EXISTS "api_keys" (
       "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
       "description" text DEFAULT '' NOT NULL,
       "consumer_key_hash" text NOT NULL,
       "consumer_secret_hash" text NOT NULL,
       "truncated_key" text DEFAULT '' NOT NULL,
       "permissions" "api_key_permission" DEFAULT 'read' NOT NULL,
       "last_access" timestamp,
       "created_at" timestamp DEFAULT now() NOT NULL,
       "revoked_at" timestamp
     )`,
  ],
  [
    'index idx_api_keys_consumer_key',
    `CREATE UNIQUE INDEX IF NOT EXISTS "idx_api_keys_consumer_key"
       ON "api_keys" USING btree ("consumer_key_hash")`,
  ],

  [
    'api_keys.woo_key_id',
    `ALTER TABLE "api_keys" ADD COLUMN IF NOT EXISTS "woo_key_id" integer
       GENERATED BY DEFAULT AS IDENTITY`,
  ],
  [
    'api_keys.consumer_secret_enc',
    `ALTER TABLE "api_keys" ADD COLUMN IF NOT EXISTS "consumer_secret_enc" text`,
  ],

  [
    'table woo_oauth_nonces',
    `CREATE TABLE IF NOT EXISTS "woo_oauth_nonces" (
       "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
       "key_id" uuid NOT NULL REFERENCES "api_keys"("id") ON DELETE cascade,
       "nonce" text NOT NULL,
       "timestamp" integer NOT NULL,
       "created_at" timestamp DEFAULT now() NOT NULL
     )`,
  ],
  [
    'index idx_woo_oauth_nonce',
    `CREATE UNIQUE INDEX IF NOT EXISTS "idx_woo_oauth_nonce"
       ON "woo_oauth_nonces" USING btree ("key_id", "nonce")`,
  ],
  [
    'index idx_woo_oauth_nonce_time',
    `CREATE INDEX IF NOT EXISTS "idx_woo_oauth_nonce_time"
       ON "woo_oauth_nonces" USING btree ("created_at")`,
  ],

  [
    'table order_notes',
    `CREATE TABLE IF NOT EXISTS "order_notes" (
       "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
       "order_id" uuid NOT NULL REFERENCES "orders"("id") ON DELETE cascade,
       "note" text NOT NULL,
       "customer_note" boolean DEFAULT false NOT NULL,
       "author" text DEFAULT 'system' NOT NULL,
       "created_at" timestamp DEFAULT now() NOT NULL
     )`,
  ],
  [
    'index idx_order_notes_order',
    `CREATE INDEX IF NOT EXISTS "idx_order_notes_order"
       ON "order_notes" USING btree ("order_id", "created_at")`,
  ],

  [
    'table integration_events',
    `CREATE TABLE IF NOT EXISTS "integration_events" (
       "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
       "source" text DEFAULT 'woo' NOT NULL,
       "method" text NOT NULL,
       "path" text NOT NULL,
       "status_code" integer DEFAULT 0 NOT NULL,
       "ip" text,
       "user_agent" text,
       "body" jsonb,
       "created_at" timestamp DEFAULT now() NOT NULL
     )`,
  ],
  [
    'index idx_integration_events_time',
    `CREATE INDEX IF NOT EXISTS "idx_integration_events_time"
       ON "integration_events" USING btree ("created_at")`,
  ],
  [
    'index idx_integration_events_status',
    `CREATE INDEX IF NOT EXISTS "idx_integration_events_status"
       ON "integration_events" USING btree ("status_code", "created_at")`,
  ],

  // Identity columns backfill existing rows with sequential values on ADD.
  [
    'orders.woo_id',
    `ALTER TABLE "orders" ADD COLUMN IF NOT EXISTS "woo_id" integer
       GENERATED BY DEFAULT AS IDENTITY`,
  ],
  [
    'index idx_orders_woo_id',
    `CREATE UNIQUE INDEX IF NOT EXISTS "idx_orders_woo_id"
       ON "orders" USING btree ("woo_id")`,
  ],
  ['orders.label_url', `ALTER TABLE "orders" ADD COLUMN IF NOT EXISTS "label_url" text`],
  ['orders.shipment_id', `ALTER TABLE "orders" ADD COLUMN IF NOT EXISTS "shipment_id" text`],
  ['orders.shipped_at', `ALTER TABLE "orders" ADD COLUMN IF NOT EXISTS "shipped_at" timestamp`],
  ['orders.delivered_at', `ALTER TABLE "orders" ADD COLUMN IF NOT EXISTS "delivered_at" timestamp`],
  ['orders.external_source', `ALTER TABLE "orders" ADD COLUMN IF NOT EXISTS "external_source" text`],

  [
    'products.woo_product_id',
    `ALTER TABLE "products" ADD COLUMN IF NOT EXISTS "woo_product_id" integer
       GENERATED BY DEFAULT AS IDENTITY`,
  ],
  [
    'index idx_products_woo_id',
    `CREATE UNIQUE INDEX IF NOT EXISTS "idx_products_woo_id"
       ON "products" USING btree ("woo_product_id")`,
  ],
];

async function main() {
  console.log(
    `\nPirate Ship connector schema → ${host}${DRY_RUN ? '  (dry run)' : ''}\n`
  );

  for (const [label, sql] of steps) {
    if (DRY_RUN) {
      console.log(`  would apply: ${label}`);
      continue;
    }
    try {
      await query(sql);
      console.log(`  ok   ${label}`);
    } catch (error) {
      console.error(`  FAIL ${label}: ${error.message}`);
      process.exit(1);
    }
  }

  console.log(
    DRY_RUN ? '\nDry run complete. Nothing was changed.\n' : '\nSchema applied.\n'
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
